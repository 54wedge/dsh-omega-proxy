#!/usr/bin/env node
// Concatenate src/client/*.js into the single client bundle the Harness module
// loader serves. One file per concern; ORDER is the only coupling between them:
// they share the factory scope, so runtime.js must come first and entry.js last.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ORDER = [
  'runtime.js',    // requires, shared handles, constants
  'strings.js',    // locale dictionaries
  'styles.js',     // stylesheet
  'localize.js',   // t from slot props
  'api.js',        // HTTP client, error boundary
  'controls.js',   // Select, color swatches
  'chip.js',       // header chip
  'model.js',      // draft conversion, summary
  'cards.js',      // profile and plugin rows
  'settings.js',   // settings page
  'dialog.js',     // profile editor
  'entry.js',      // inject + apply
]

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const sourceDir = path.join(root, 'src', 'client')
const target = path.join(root, 'client.js')

const present = fs.readdirSync(sourceDir).filter(name => name.endsWith('.js')).sort()
const missing = present.filter(name => !ORDER.includes(name))
const absent = ORDER.filter(name => !present.includes(name))
if (missing.length > 0 || absent.length > 0) {
  console.error(`src/client is out of sync with ORDER (missing: ${missing.join(', ') || 'none'}; absent: ${absent.join(', ') || 'none'})`)
  process.exit(1)
}

const body = ORDER
  .map(name => fs.readFileSync(path.join(sourceDir, name), 'utf8').trimEnd())
  .join('\n\n')

const bundle = `// Generated by scripts/build-client.mjs from src/client/*.js — do not edit.
window.__ModuleLoader__.load({
  id: 'dsh-omega-proxy',
  factory(require) {
${body}

    return { inject, apply }
  },
})
`

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (current !== bundle) {
    console.error('client.js is stale — run: node scripts/build-client.mjs')
    process.exit(1)
  }
  console.log('client.js is up to date')
} else {
  fs.writeFileSync(target, bundle)
  console.log(`client.js ← ${ORDER.length} sources (${bundle.split('\n').length} lines)`)
}
